// Keep the original default export compatible with product card grids.
const products = productLists.flatMap((list) => list.products);

/**
 * Retrieves a category heading and its ten mock products.
 * @param {string} categoryId - The dropdown category ID.
 * @returns {Promise<(typeof productLists)[number]|null>} List or null.
 */
export async function getProductList(categoryId) {
  return productLists.find((list) => list.id === categoryId) ?? null;
}

/**
 * Retrieves mock products. No HTTP request is made.
 * @param {string} [categoryId="all"] - A dropdown category ID or "all".
 * @returns {Promise<typeof products>} Matching products.
 */
export async function getProducts(categoryId = "all") {
  return products.filter(
    (product) => categoryId === "all" || product.category === categoryId,
  );
}

/**
 * Retrieves a mock product using an ID or route parameter.
 * @param {number|string} id - The product ID.
 * @returns {Promise<(typeof products)[number]|null>} Product or null.
 */
export async function getProductById(id) {
  return products.find((product) => product.id === Number(id)) ?? null;
}

export default products;
